export function scenarioUrl(keyword: string): string {
  return keyword
    ? `https://videos.example.com/watch/${keyword}`
    : "https://videos.example.com/watch/sample";
}

/**
 * Longest keyword wins, so `probetimeout` is not shadowed by a future
 * `timeout` entry.
 */
export function findScenario(url: string): Scenario {
  let segments: string[];
  try {
    segments = new URL(url).pathname
      .split("/")
      .filter(Boolean)
      .map((s) => s.toLowerCase());
  } catch {
    return DEFAULT_SCENARIO;
  }
  const matches = SCENARIOS.filter((scenario) => segments.includes(scenario.keyword));
  matches.sort((a, b) => b.keyword.length - a.keyword.length);
  return matches[0] ?? DEFAULT_SCENARIO;
}
