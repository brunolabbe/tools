/**
 * Demo scenarios for the mock transport.
 *
 * Selection is by *path segment* of the pasted URL, not substring, so a real
 * URL that happens to contain the word "live" still gets the happy path. Every
 * `ErrorCode` in the taxonomy is reachable from this table plus three
 * interactions the table cannot express (bad input, cancel, unknown job) —
 * see `docs`-free note in `SCENARIOS` entries below.
 */

import type {
  ErrorCode,
  JobStatus,
  MediaVariant,
  ProbeResult,
  SubtitleTrack,
} from "@downloader/contract";

/** How the mock should play out a job once it has been created. */
export interface JobScript {
  failWith?: ErrorCode;
  /** Stage at which `failWith` is emitted. */
  failAt?: JobStatus;
  /** Report `percent: null` throughout — live capture, no Content-Length. */
  indeterminate?: boolean;
  /** Download tick indices at which the SSE connection is dropped. */
  dropStreamAt?: readonly number[];
  /** Publish a result whose retention window has already closed. */
  expiredResult?: boolean;
}

export interface Scenario {
  /** Matched against the pasted URL's path segments. */
  keyword: string;
  title: string;
  description: string;
  probeDelayMs: number;
  /** When set, the probe rejects with this code instead of returning a result. */
  probeError?: ErrorCode;
  /** Applied to the baseline probe result. */
  probe?: (base: ProbeResult) => ProbeResult;
  job: JobScript;
}

